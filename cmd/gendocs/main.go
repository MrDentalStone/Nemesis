// gendocs writes docs/TOOLS.md from the tools the server registers and
// docs/DECKS.md from modes/ and decks/, so neither drifts from the source.
//
//	go run ./cmd/gendocs
package main

import (
	"context"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"

	"github.com/modelcontextprotocol/go-sdk/mcp"

	"github.com/MrDentalStone/Nemesis"
	"github.com/MrDentalStone/Nemesis/internal/content"
	"github.com/MrDentalStone/Nemesis/internal/mcpserver"
)

// sections group the tools in the order a reader meets them.
var sections = []struct {
	title string
	tools []string
}{
	{"Reading the table", []string{"table_state", "my_hand", "wait_for_event", "parse_card", "tts_log"}},
	{"Talking to the table", []string{"say", "ask_table", "cancel_round", "player_pads", "claim_seat"}},
	{"Playbook, modes and decks", []string{"playbook", "list_modes", "mode_rules", "list_decks", "deck_info", "import_deck"}},
	{"Your cards", []string{"begin_turn", "cast", "draw", "mulligan", "shuffle_library", "play", "tap", "untap", "flip", "move", "attack", "end_turn"}},
	{"Library effects", []string{"look", "search_library", "reveal_until", "reveal"}},
	{"Counters, tokens and life", []string{"mark", "counter", "spawn_token", "adjust_life", "reset_life", "commander_damage"}},
	{"Setting up and between games", []string{"setup_pad", "reset_board"}},
	{"Development only (-dev)", []string{"exec_lua"}},
}

func main() {
	srv := mcp.NewServer(&mcp.Implementation{Name: "nemesis", Version: "docs"}, nil)
	mcpserver.Register(srv, mcpserver.Deps{Content: content.Load(nemesis.Files), Docs: nemesis.Files, Name: "Kestrel", Dev: true})

	ctx := context.Background()
	ct, st := mcp.NewInMemoryTransports()
	if _, err := srv.Connect(ctx, st, nil); err != nil {
		log.Fatal(err)
	}
	cs, err := mcp.NewClient(&mcp.Implementation{Name: "gendocs"}, nil).Connect(ctx, ct, nil)
	if err != nil {
		log.Fatal(err)
	}
	res, err := cs.ListTools(ctx, nil)
	if err != nil {
		log.Fatal(err)
	}
	tools := map[string]*mcp.Tool{}
	for _, t := range res.Tools {
		tools[t.Name] = t
	}

	var b strings.Builder
	b.WriteString("# Nemesis MCP tools\n\n")
	b.WriteString("Generated by `go run ./cmd/gendocs` from the server's own tool list; do not edit by hand.\n\n")
	b.WriteString("Nemesis is a stdio MCP server. Every tool returns plain text written for the AI to read. ")
	b.WriteString("Tools that act on the table go through the Nemesis pad in Tabletop Simulator, which refuses anything outside the AI's own seat, ")
	b.WriteString("and every action is refused while the pad's STOP button is on.\n\n")
	done := map[string]bool{}
	for _, sec := range sections {
		fmt.Fprintf(&b, "## %s\n\n", sec.title)
		for _, name := range sec.tools {
			if t := tools[name]; t != nil {
				writeTool(&b, t)
				done[name] = true
			}
		}
	}
	var rest []string
	for name := range tools {
		if !done[name] {
			rest = append(rest, name)
		}
	}
	if len(rest) > 0 {
		sort.Strings(rest)
		b.WriteString("## Other\n\n")
		for _, name := range rest {
			writeTool(&b, tools[name])
		}
	}
	if err := os.WriteFile("docs/TOOLS.md", []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("docs/TOOLS.md: %d tools\n", len(tools))
	writeDecks()
}

func writeDecks() {
	lib := content.Load(nemesis.Files)
	var b strings.Builder
	b.WriteString("# Modes and decks\n\n")
	b.WriteString("Generated by `go run ./cmd/gendocs` from `modes/` and `decks/`; do not edit by hand. ")
	b.WriteString("Every deck passes `go run ./cmd/deckcheck -importer`: 100 cards, singleton, Commander-legal, inside the colour identity, ")
	b.WriteString("Game Changers within its bracket, and it builds on the deck importer. See [CONTENT.md](CONTENT.md) to add your own.\n\n")
	b.WriteString("| Mode | What it means | Decks |\n|---|---|---|\n")
	for _, m := range lib.SortedModes() {
		def := ""
		if m.Default {
			def = " (default)"
		}
		fmt.Fprintf(&b, "| **%s**%s `%s` | %s | %d |\n", m.Name, def, m.ID, m.Blurb, len(lib.DecksFor(m.ID)))
	}
	b.WriteString("\n| Deck | Commander | Colours | Bracket | Modes | Summary |\n|---|---|---|---|---|---|\n")
	all := lib.DecksFor("")
	for _, d := range all {
		fmt.Fprintf(&b, "| [%s](../decks/%s.md) | %s | %s | %s | %s | %s |\n", d.Name, d.ID, d.Commander, d.Colors, d.Bracket,
			strings.Join(lib.ModesOf(d), ", "), d.Summary)
	}
	if err := os.WriteFile("docs/DECKS.md", []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("docs/DECKS.md: %d modes, %d decks\n", len(lib.Modes), len(all))
}

func writeTool(b *strings.Builder, t *mcp.Tool) {
	fmt.Fprintf(b, "### `%s`\n\n%s\n\n", t.Name, t.Description)
	raw, _ := json.Marshal(t.InputSchema)
	var schema struct {
		Properties map[string]struct {
			Type        any    `json:"type"`
			Description string `json:"description"`
		} `json:"properties"`
		Required []string `json:"required"`
	}
	json.Unmarshal(raw, &schema)
	if len(schema.Properties) == 0 {
		b.WriteString("No parameters.\n\n")
		return
	}
	req := map[string]bool{}
	for _, r := range schema.Required {
		req[r] = true
	}
	names := make([]string, 0, len(schema.Properties))
	for n := range schema.Properties {
		names = append(names, n)
	}
	sort.Slice(names, func(i, j int) bool {
		if req[names[i]] != req[names[j]] {
			return req[names[i]]
		}
		return names[i] < names[j]
	})
	b.WriteString("| Parameter | Type | Description |\n|---|---|---|\n")
	for _, n := range names {
		p := schema.Properties[n]
		typ := fmt.Sprint(p.Type)
		if arr, ok := p.Type.([]any); ok {
			parts := make([]string, len(arr))
			for i, v := range arr {
				parts[i] = fmt.Sprint(v)
			}
			typ = strings.Join(parts, " or ")
		}
		name := "`" + n + "`"
		if req[n] {
			name += " (required)"
		}
		fmt.Fprintf(b, "| %s | %s | %s |\n", name, typ, strings.ReplaceAll(p.Description, "|", "\\|"))
	}
	b.WriteString("\n")
}
